#!/usr/bin/env python3
"""Generate an opt-in template registry; the default production registry is unchanged."""
import argparse
import json
from pathlib import Path


def registry():
    text = Path("solution/sw/fp32/sw_fp32_batch.h").read_text()
    block = text.split("using KernelConfigurations=std::tuple<", 1)[1].split("\n>;", 1)[0]
    controls = [line.strip().split(">", 1)[0] + ">" for line in block.splitlines()
                if line.strip().startswith("KernelConfig<")]
    entries = list(controls)

    def add(bm, bn, bk, tm, tn, wm, wn, ck, gm=1, fused=False,
            persistent=False, raw=False, slots=2):
        strategy = "CooperativeFused" if fused else "DirectBMaterialized"
        if fused:
            shared = max(7 * bk * (bm + bn) * 4 * slots, 7 * bm * bn * 4) + 128
            if shared > 224 * 1024:
                return
        values = [bm, bn, bk, tm, tn, wm, wn, ck, gm,
                  "ExecutionStrategy::" + strategy, persistent,
                  0 if fused else 3, True, not fused, raw, slots]
        def fmt(value):
            return str(value).lower() if isinstance(value, bool) else str(value)
        candidate = "KernelConfig<" + ",".join(map(fmt, values)) + ">"
        # Expand omitted default arguments to avoid duplicate controls.
        def canonical(entry):
            parts = entry[len("KernelConfig<"):-1].split(",")
            defaults = ["ExecutionStrategy::Materialized", "false", "0", "false", "false", "false", "2"]
            return parts + defaults[len(parts) - 9:]
        if all(canonical(candidate) != canonical(e) for e in entries):
            entries.append(candidate)

    # Keep 8x8 thread reuse while sweeping CTA geometry and K staging.
    for wm, wn in [(1, 1), (1, 2), (2, 1), (1, 4), (2, 2), (2, 4), (4, 1), (4, 2)]:
        for bk in (16, 32):
            add(64 * wm, 32 * wn, bk, 8, 8, wm, wn, 16, 4)
    # Separate instruction expansion and CTA scheduling from the tile sizes.
    for ck in (8, 16, 32):
        for gm in (1, 4, 8):
            add(128, 64, 32, 8, 8, 2, 2, ck, gm)
    for ck in (8, 32):
        for gm in (1, 8):
            add(64, 128, 32, 8, 8, 1, 4, ck, gm)
    # Existing fused body, including the guards and fully packed fallback.
    for bm, bn, tm, tn in [(64, 32, 8, 8), (32, 64, 8, 8),
                           (128, 16, 8, 8), (16, 64, 4, 8), (64, 16, 8, 4)]:
        for bk in (16, 32):
            add(bm, bn, bk, tm, tn, 1, 1, 16, fused=True, raw=True)
    for bm, bn in [(64, 32), (32, 64)]:
        for bk, ck, slots in [(8, 8, 2), (8, 8, 4), (16, 8, 2),
                              (16, 16, 3), (16, 16, 4), (32, 8, 2)]:
            add(bm, bn, bk, 8, 8, 1, 1, ck, fused=True, raw=True, slots=slots)
        for bk in (16, 32):
            add(bm, bn, bk, 8, 8, 1, 1, 16, fused=True, persistent=True, raw=True)
    return entries, len(controls)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--ids", help="Comma-separated IDs from the generated registry")
    args = parser.parse_args()
    entries, controls = registry()
    ids = list(range(len(entries))) if args.ids is None else list(map(int, args.ids.split(",")))
    if not ids or len(set(ids)) != len(ids) or any(i < 0 or i >= len(entries) for i in ids):
        parser.error("IDs must be unique entries in the generated registry")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("// Generated by scripts/sweep_fp32_configs.py\n" + ",\n".join(entries[i] for i in ids) + "\n")
    manifest = [{"id": j, "sweep_id": i, "control": i < controls, "template": entries[i]}
                for j, i in enumerate(ids)]
    args.output.with_suffix(".json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Generated {len(ids)} templates ({sum(i < controls for i in ids)} controls): {args.output}")


if __name__ == "__main__":
    main()
