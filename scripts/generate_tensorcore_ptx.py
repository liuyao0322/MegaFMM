#!/usr/bin/env python3
"""Emit literal PTX operand lists for one configurable WGMMA consumer.

CUDA inline asm requires literal register tuples. Only those tuples and the
per-fragment unrolled reconstruction are generated; tile scheduling, barriers,
K loops and the seven-product algorithm have one shared definition below.
No matrix dimensions, dispatch IDs or independent kernels are generated.
"""
from pathlib import Path
import argparse
WIDTHS=(8,16,32,64,96,128,160,192)
out=['// Generated by scripts/generate_tensorcore_ptx.py. Do not edit.\n',
     '#define TC_STR0(x) #x\n#define TC_STR(x) TC_STR0(x)\n#define TC_CAT0(a,b) a##b\n#define TC_CAT(a,b) TC_CAT0(a,b)\n']
def macro(name,lines):
 out.append('#define '+name+' \\\n')
 for i,line in enumerate(lines):out.append('  '+line+(' \\\n' if i<len(lines)-1 else '\n'))
def asm(lines):return ['"'+s+'\\n"' for s in lines]
for width_index,n in enumerate(WIDTHS):
 count=n//2
 previous=WIDTHS[width_index-1]//2 if width_index else 0
 out.append(f'#define TC_REGS_{count} "'+','.join('d'+str(i) for i in range(count))+'"\n')
 for step in range(7):
  lines=[]
  for j in range(previous,count):
   if step==0:lines += [f'mov.f32 first{j},d{j};']
   elif step==2:lines += [f'add.rn.f32 first{j},first{j},d{j};']
   elif step==3:lines += [f'setp.lt.u32 shared,{j},%[shared];',f'add.rn.f32 x,first{j},d{j};',f'@shared st.shared.f32 [u3+{j*512}],x;',f'@!shared mov.f32 second{j},x;']
   else:
    if step in (1,5):lines += [f'add.rn.f32 x,first{j},d{j};']
    else:
     lines += [f'setp.lt.u32 shared,{j},%[shared];',f'@shared ld.shared.f32 x,[u3+{j*512}];',f'@!shared mov.f32 x,second{j};']
     lines += [f'{"add" if step==4 else "sub"}.rn.f32 x,x,d{j};']
     if step==4:lines += [f'add.rn.f32 first{j},first{j},d{j};']
    ro=(j%2)+(j//4)*8;co=((j//2)%2)*8
    lines += [f'mad.wide.u32 dst,{ro},%[ld],%[out];',f'add.u64 dst,dst,{co*4};',
              f'add.u32 gr,%[row],{ro};',f'add.u32 gc,%[col],{co};',
              'setp.lt.u32 valid,gr,%[mh];','setp.lt.u32 tmp,gc,%[nh];','and.pred valid,valid,tmp;']
    if step in (4,6):lines += ['add.u64 dst,dst,%[rowoff];','add.u32 gr,gr,%[mh];']
    if step in (4,5):lines += ['add.u64 dst,dst,%[coloff];','add.u32 gc,gc,%[nh];']
    lines += ['setp.lt.u32 tmp,gr,%[M];','and.pred valid,valid,tmp;','setp.lt.u32 tmp,gc,%[N];','and.pred valid,valid,tmp;','or.pred valid,valid,bypass;','@valid st.global.f32 [dst],x;']
  macro(f'TC_RECON_{step}_{count}',([f'TC_RECON_{step}_{previous}'] if previous else [])+asm(lines))
# Each primitive gets the same private register tuple, parameterized by native
# operand type and WGMMA width. The first K16 operation uses the passed predicate.
for k in range(16):
 macro(f'TC_MMA_{k}(N,DT,R,ACC)',[
  f'"@low32 add.u32 dl,at,%[da{k}];\\n"', '"@low32 mov.b64 da,{dl,ahi};\\n"',
  f'"@low32 add.u32 el,bt,%[db{k}];\\n"', '"@low32 mov.b64 db,{el,bhi};\\n"',
  f'"@!low32 add.u64 da,ba,%[da{k}];\\n"', f'"@!low32 add.u64 db,bb,%[db{k}];\\n"',
  '"wgmma.mma_async.sync.aligned.m64n" TC_STR(N) "k16.f32." DT "." DT " {" R "},da,db," ACC ",1,1,%[major_a],%[major_b];\\n"'])
for bk in (64,128,256):
 macro(f'TC_K_{bk}(N,DT,R,ACC)',[f'TC_MMA_{k}(N,DT,R,{"ACC" if k==0 else chr(34)+"always"+chr(34)})' for k in range(bk//16)])
macro('TC_FENCE',asm(['wgmma.fence.sync.aligned;']))
out.append('#define TC_NOFENCE\n')
macro('TC_TILE(LABEL,N,DT,K,R,ACC,FENCE)',asm([
 'rem.u32 slot,sequence,%[stages];','div.u32 phase,sequence,%[stages];','and.b32 phase,phase,1;',
 'shl.b32 offset,slot,3;','add.u32 rb,%[ready],offset;',
 'setp.ge.u32 release,q,%[pending];','and.pred release,release,leader;',
 'sub.u32 previous,sequence,%[pending];','rem.u32 previous,previous,%[stages];',
 'shl.b32 offset,previous,3;','add.u32 fb,%[free],offset;',
 ])+['"WAIT_" LABEL ":\\n"']+asm([
 'mbarrier.try_wait.parity.shared::cta.b64 done,[rb],phase,0x989680;',
 ])+['"@!done bra WAIT_" LABEL ";\\n"']+asm([
 'mul.lo.u32 offset,slot,%[slot_stride];','add.u32 at,alo,offset;','add.u32 bt,blo,offset;',
 'cvt.u64.u32 offset64,offset;','add.u64 ba,%[a],offset64;','add.u64 bb,%[b],offset64;',
 ])+['FENCE','TC_CAT(TC_K_,K)(N,DT,R,ACC)']+asm([
 'wgmma.commit_group.sync.aligned;','wgmma.wait_group.sync.aligned %[pending];',
 'bar.warp.sync 0xffffffff;',
 '@release mbarrier.arrive.shared::cta.b64 _,[fb];','add.u32 sequence,sequence,1;']))
macro('TC_STEP(STEP,N,DT,K,R,COUNT)',[
 '"mov.u32 q,0;\\n"','TC_TILE(TC_STR(STEP) "_FIRST",N,DT,K,R,"noacc",TC_FENCE)',
 '"mov.u32 q,1;\\n"','"setp.ge.u32 more,q,%[kt];\\n"','"@more bra DONE_" TC_STR(STEP) ";\\n"',
 '"LOOP_" TC_STR(STEP) ":\\n"','TC_TILE(TC_STR(STEP) "_REST",N,DT,K,R,"always",TC_FENCE)',
 '"add.u32 q,q,1;\\n"','"setp.lt.u32 more,q,%[kt];\\n"','"@more bra LOOP_" TC_STR(STEP) ";\\n"',
 '"DONE_" TC_STR(STEP) ":\\n"']+asm([
 'wgmma.wait_group.sync.aligned 0;','sub.u32 previous,sequence,1;','rem.u32 previous,previous,%[stages];','shl.b32 offset,previous,3;',
 'add.u32 fb,%[free],offset;','bar.warp.sync 0xffffffff;','@last_release mbarrier.arrive.shared::cta.b64 _,[fb];'
 ])+['TC_CAT(TC_CAT(TC_RECON_,STEP),TC_CAT(_,COUNT))'])
# A bounded compile-time K loop reuses exactly the same stage primitive.
final_release=asm([
 'wgmma.wait_group.sync.aligned 0;','sub.u32 previous,sequence,1;','rem.u32 previous,previous,%[stages];','shl.b32 offset,previous,3;',
 'add.u32 fb,%[free],offset;','bar.warp.sync 0xffffffff;','@last_release mbarrier.arrive.shared::cta.b64 _,[fb];'])
macro('TC_STEP4(STEP,N,DT,K,R,COUNT)',sum(([
 f'"mov.u32 q,{q};\\n"',
 f'TC_TILE(TC_STR(STEP) "_Q{q}",N,DT,K,R,"'+('noacc' if q==0 else 'always')+'",TC_FENCE)'] for q in range(4)),[])+final_release+['TC_CAT(TC_CAT(TC_RECON_,STEP),TC_CAT(_,COUNT))'])
preamble=[
 '"{ .reg .pred noacc,always,leader,done,more,shared,valid,tmp,release,last_release,bypass,low32;\\n"',
 '".reg .b64 da,db,dst,ba,bb,offset64;\\n"',
 '".reg .b32 alo,ahi,blo,bhi,at,bt,dl,el;\\n"',
 '".reg .b32 q,sequence,slot,phase,offset,rb,fb,previous,u3,gr,gc;\\n"',
 '".reg .f32 d<" TC_STR(COUNT) ">,first<" TC_STR(COUNT) ">,second<" TC_STR(COUNT) ">,x;\\n"']+asm([
 'mov.b64 {alo,ahi},%[a];','mov.b64 {blo,bhi},%[b];','setp.eq.u32 noacc,1,0;','setp.ne.u32 always,1,0;','setp.eq.u32 leader,%[lane],0;',
 'setp.ne.u32 shared,%[shared],0;','setp.ne.u32 last_release,%[pending],0;','and.pred last_release,last_release,leader;',
 'setp.ne.u32 low32,%[low32],0;','setp.eq.u32 bypass,%[guard],0;','mov.u32 sequence,0;','mov.u32 u3,%[u3];'])
macro('TC_BODY(N,DT,K,COUNT,STEP_FN)',preamble+[f'STEP_FN({i},N,DT,K,TC_CAT(TC_REGS_,COUNT),COUNT)' for i in range(7)]+['"}\\n"'])
# With one K tile, seven independent accumulators permit wait1 across products.
# This is a schedule of the same seven terms, not a separate matrix-size kernel.
for n in WIDTHS:
 count=n//2
 for step in range(7):
  out.append(f'#define TC_SHORT_REGS_{step}_{count} "'+','.join(f'p{step}d{j}' for j in range(count))+'"\n')
  macro(f'TC_SHORT_COPY_{step}_{count}',asm([f'mov.f32 d{j},p{step}d{j};' for j in range(count)]))
short_declarations=['".reg .f32 p'+str(i)+'d<" TC_STR(COUNT) ">;\\n"' for i in range(7)]
short_issue=sum(([
 f'"mov.u32 q,{i};\\n"',f'TC_TILE("SHORT_{i}",N,DT,K,TC_CAT(TC_SHORT_REGS_{i}_,COUNT),"noacc",TC_NOFENCE)'] for i in range(7)),[])
short_recon=sum(([f'TC_CAT(TC_SHORT_COPY_{i}_,COUNT)',f'TC_CAT(TC_RECON_{i}_,COUNT)'] for i in range(7)),[])
macro('TC_BODY_SHORT(N,DT,K,COUNT)',preamble+short_declarations+['TC_FENCE']+short_issue+final_release+short_recon+['"}\\n"'])
inputs=['[a] "l"(uint64_t(da_tiles(0,0,0)))','[b] "l"(uint64_t(db_tiles(0,0,0)))',
 '[ready] "r"(uint32_t(__cvta_generic_to_shared(s.ready)))','[free] "r"(uint32_t(__cvta_generic_to_shared(s.free)))',
 '[lane] "r"(uint32_t(threadIdx.x%32))','[out] "l"(out)','[ld] "r"(uint32_t(N*4))',
 '[rowoff] "l"(uint64_t(mh)*N*4)','[coloff] "l"(uint64_t(nh)*4)',
 '[row] "r"(uint32_t(row))','[col] "r"(uint32_t(col))','[mh] "r"(uint32_t(mh))','[nh] "r"(uint32_t(nh))',
 '[M] "r"(uint32_t(M))','[N] "r"(uint32_t(N))','[kt] "r"(uint32_t(kt))',
 '[low32] "n"(int(C::k_tiles==1))','[guard] "n"(int(C::guard_outputs))','[stages] "n"(C::stages)','[pending] "n"(int(C::pending))','[shared] "n"(C::u3_components)',
 '[slot_stride] "n"(2*(64*C::groups+C::n)*C::bk/16)',
 '[u3] "r"(uint32_t(__cvta_generic_to_shared(s.u3+(C::shared_u3?(group*C::u3_components*128+lane):0))))',
 '[major_a] "n"(int32_t(GMMA::Major::MN))','[major_b] "n"(int32_t(GMMA::Major::K))']
for i in range(16):
 inputs += [f'[da{i}] "n"(uint32_t(da_tiles.layout()(0,0,Int<{i}%(C::bk/16)>{{}})))',f'[db{i}] "n"(uint32_t(db_tiles.layout()(0,0,Int<{i}%(C::bk/16)>{{}})))']
macro('TC_INPUTS', [v+(',' if i<len(inputs)-1 else '') for i,v in enumerate(inputs)])
macro('TC_INVOKE(N,DT,K,COUNT)', [
 'if constexpr(C::k_tiles==1) {asm volatile(TC_BODY_SHORT(N,DT,K,COUNT) : : TC_INPUTS : "memory");}',
 'else if constexpr(C::k_tiles==4) {asm volatile(TC_BODY(N,DT,K,COUNT,TC_STEP4) : : TC_INPUTS : "memory");}',
 'else {asm volatile(TC_BODY(N,DT,K,COUNT,TC_STEP) : : TC_INPUTS : "memory");}'])
out.append('''
template<class T,class C> __device__ __forceinline__
void consume(Shared<T,C>& s,int group,int m0,int n0,Shape z,float* D,int M,int N) {
  using namespace cute;
  constexpr int Count=C::n/2;
  constexpr auto la=tile_to_shape(GMMA::Layout_MN_SW128_Atom<T>{},cute::Shape<_64,Int<C::bk>>{});
  constexpr auto lb=tile_to_shape(GMMA::Layout_K_SW128_Atom<T>{},cute::Shape<Int<C::n>,Int<C::bk>>{});
  auto a=make_tensor(make_smem_ptr(s.operand[0]+group*64*C::bk),la);
  auto b=make_tensor(make_smem_ptr(s.operand[0]+64*C::groups*C::bk),lb);
  auto da_tiles=make_tensor<GMMA::smem_desc<GMMA::Major::MN>>(tiled_divide(a,cute::Shape<_64,_16>{}));
  auto db_tiles=make_tensor<GMMA::smem_desc<GMMA::Major::K>>(tiled_divide(b,cute::Shape<Int<C::n>,_16>{}));
  int lane=threadIdx.x%128;
  int row=n0+(lane%4)*2,col=m0+group*64+(lane/4)%8+(lane/32)*16;
  int mh=(M+1)/2,nh=(N+1)/2,kt=C::k_tiles?C::k_tiles:z.kh/C::bk;
  float* out=D+int64_t(row)*N+col;
''')
for i,n in enumerate(WIDTHS):
 out.append(f'  {"if" if i==0 else "else if"} constexpr(C::n=={n}) {{\n')
 for j,bk in enumerate((64,128,256)):
  out.append(f'    {"if" if j==0 else "else if"} constexpr(C::bk=={bk}) {{\n')
  out.append(f'      if constexpr(std::is_same_v<T,bfloat16_t>) {{TC_INVOKE({n},"bf16",{bk},{n//2})}}\n')
  out.append(f'      else {{TC_INVOKE({n},"f16",{bk},{n//2})}}\n    }}\n')
 out.append('  }\n')
out.append('  else {static_assert(C::n==0,"unsupported WGMMA width");}\n}\n')
# Avoid leaking implementation macros into the kernel/translation unit.
import re
names=re.findall(r'^#define (\w+)', ''.join(out),re.M)
out += ['#undef '+n+'\n' for n in names]
text=''.join(out)
# NVCC 12.4 supports positional, not GCC symbolic, inline-asm operands.
operand_names=[re.match(r'\[(\w+)\]',x).group(1) for x in inputs]
for index,name in enumerate(operand_names):
 text=text.replace('%['+name+']','%'+str(index))
text=re.sub(r'\[('+'|'.join(operand_names)+r')\] (?="[lrn]")','',text)
p=Path(__file__).resolve().parents[1]/'solution/sw/hopper/sw_tensorcore_ptx.cuh'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
if args.check:
 assert p.read_text()==text,'generated PTX header is stale'
else:p.write_text(text)
print(f'{"Verified" if args.check else "Generated"} {p.name}: one consumer template, {len(text)} bytes')
