"""Generate a research-only direct-input Hopper kernel; no solution edits.

Four output quadrants, each with its original full K dot product. Eight block
products replace seven Winograd products, eliminating transform rounding.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate(bn=32, overlap=False):
    stages={32:8,64:6,128:4}[bn]
    quads=128//bn
    nregs=bn//2
    ctype=f'GMMA::CLayout_64x{bn}'
    source = (ROOT/'solution/sw_pipeline.cu').read_text()
    encode = source[source.index('void encode('):source.index('} // namespace\nstruct SWState')]
    out = '''// Generated by generate_direct.py. Research-only, dense eight-product algorithm.
#include "internal.h"
#include <cuda.h>
#include <cute/tensor.hpp>
#include <cute/atom/mma_traits_sm90_gmma.hpp>
#include <cute/arch/copy_sm90_tma.hpp>
#include <cutlass/arch/barrier.h>
#include <stdexcept>
#include <type_traits>
namespace precision_research {
using megafmm::DType;
constexpr int BM=64, BN=32, BK=128, Stages=8, Threads=256;
constexpr int ASize=BM*BK, BSize=BN*BK;
using Barrier=cutlass::arch::ClusterBarrier;
using TxBarrier=cutlass::arch::ClusterTransactionBarrier;
template<class T> struct alignas(128) Shared {
  T operand[Stages][ASize+BSize];
  uint64_t ready[Stages],free[Stages];
};
void check(cudaError_t e,const char* where){
 if(e!=cudaSuccess)throw std::runtime_error(std::string(where)+": "+cudaGetErrorString(e));
}
template<class T> __device__ __forceinline__ void chain(Shared<T>& s,int tid,int m0,int n0,float* D){
 using namespace cute;
 constexpr auto la=tile_to_shape(GMMA::Layout_MN_SW128_Atom<T>{},Shape<_64,Int<BK>>{});
 constexpr auto lb=tile_to_shape(GMMA::Layout_K_SW128_Atom<T>{},Shape<_32,Int<BK>>{});
 auto a=make_tensor(make_smem_ptr(s.operand[0]),la);
 auto b=make_tensor(make_smem_ptr(s.operand[0]+ASize),lb);
 auto da=make_tensor<GMMA::smem_desc<GMMA::Major::MN>>(tiled_divide(a,Shape<_64,_16>{}));
 auto db=make_tensor<GMMA::smem_desc<GMMA::Major::K>>(tiled_divide(b,Shape<_32,_16>{}));
 int mn=GMMA::CLayout_64x32{}(tid-128,0);
 float* output=D+(n0+mn/64)*1024+m0+mn%64;
'''
    out=out.replace('BN=32, BK=128, Stages=8',f'BN={bn}, BK=128, Stages={stages}')
    out=out.replace('Shape<_32,Int<BK>>','Shape<Int<BN>,Int<BK>>').replace('Shape<_32,_16>','Shape<Int<BN>,_16>')
    out=out.replace('GMMA::CLayout_64x32',ctype)
    for dtype, scalar in [('bf16','cute::bfloat16_t'),('f16','cute::half_t')]:
        out += f' if constexpr(std::is_same_v<T,{scalar}>) asm volatile(\n'
        lines = ['{ .reg .pred p,zero,leader,done; .reg .b64 ba,bb,da,db,dst;',
                 f'.reg .b32 rb,fb; .reg .f32 d<{nregs}>;',
                 'setp.ne.u32 p,1,0;', 'setp.eq.u32 zero,1,0;', 'setp.eq.u32 leader,%4,0;']
        regs = ','.join(f'd{i}' for i in range(nregs))
        for quad in range(quads):
            for k in range(8):
                seq=quad*8+k
                slot=seq%stages
                phase=seq//stages%2
                lines += [f'add.u32 rb,%2,{slot*8};',f'WAIT_{seq}:',
                          f'mbarrier.try_wait.parity.shared::cta.b64 done,[rb],{phase},0x989680;',
                          f'@!done bra WAIT_{seq};',
                          *(['wgmma.fence.sync.aligned;'] if not overlap or k==0 else []),
                          f'add.u64 ba,%0,{slot*(ASize:=(64+bn)*128)*2//16};',
                          f'add.u64 bb,%1,{slot*ASize*2//16};']
                for inner in range(8):
                    acc='zero' if k==0 and inner==0 else 'p'
                    lines += [f'add.u64 da,ba,%{6+2*inner};',f'add.u64 db,bb,%{7+2*inner};',
                              f'wgmma.mma_async.sync.aligned.m64n{bn}k16.f32.{dtype}.{dtype} {{{regs}}},da,db,{acc},1,1,%{22+nregs},%{23+nregs};']
                lines += ['wgmma.commit_group.sync.aligned;', f'wgmma.wait_group.sync.aligned {1 if overlap and k<7 else 0};']
                release = ([seq-1] if k else [])+([seq] if k==7 else []) if overlap else [seq]
                if release:lines += ['bar.warp.sync 0xffffffff;']
                for freed in release:
                    lines += [f'add.u32 fb,%3,{freed%stages*8};', '@leader mbarrier.arrive.shared::cta.b64 _,[fb];']
            offset=((quad//2)*512*1024*4+(quad%2)*512*4) if bn==32 else quad*512*1024*4 if bn==64 else 0
            for i in range(nregs):
                lines += [f'add.u64 dst,%5,%{22+i};', f'add.u64 dst,dst,{offset};',f'st.global.f32 [dst],d{i};']
        lines += ['}']
        out += ''.join('  "'+v+'\\n"\n' for v in lines)
        args=['"l"(uint64_t(da(0,0,0)))','"l"(uint64_t(db(0,0,0)))',
              '"r"(uint32_t(__cvta_generic_to_shared(s.ready)))','"r"(uint32_t(__cvta_generic_to_shared(s.free)))',
              '"r"(tid&31)','"l"(output)']
        for i in range(8):
            for v in ['da','db']:
                args.append(f'"n"(uint32_t({v}.layout()(0,0,Int<{i}>{{}})))')
        for i in range(nregs):
            args.append(f'"n"(4*(int({ctype}{{}}(0,Int<{i}>{{}}))%64+(int({ctype}{{}}(0,Int<{i}>{{}}))/64)*1024))')
        args += ['"n"(int32_t(GMMA::Major::MN))','"n"(int32_t(GMMA::Major::K))']
        out += ' : : '+', '.join(args)+' : "memory");\n'
    out += '''}
template<class T> __global__ __launch_bounds__(Threads,1)
void direct_quadrants(const __grid_constant__ CUtensorMap amap,
                      const __grid_constant__ CUtensorMap bmap,float* D){
 using namespace cute;
 extern __shared__ __align__(128) unsigned char buffer[];
 auto& s=*reinterpret_cast<Shared<T>*>(buffer);
 int tid=threadIdx.x,m0=blockIdx.y*BM,n0=blockIdx.x*BN;
 if(tid==0){
   asm volatile("prefetch.tensormap [%0]; prefetch.tensormap [%1];" :: "l"(&amap),"l"(&bmap):"memory");
   for(int j=0;j<Stages;++j){Barrier::init(&s.ready[j],1);Barrier::init(&s.free[j],4);}
   cutlass::arch::fence_barrier_init();
 }
 __syncthreads();
 if(tid==0){
   for(int quad=0;quad<4;++quad) for(int k=0;k<8;++k){
     int seq=quad*8+k,slot=seq%Stages;
     if(seq>=Stages){Barrier::wait(&s.free[slot],((seq-Stages)/Stages)%2);asm volatile("":::"memory");}
     TxBarrier::arrive_and_expect_tx(&s.ready[slot],2*(ASize+BSize));
     SM90_TMA_LOAD_2D::copy(&bmap,&s.ready[slot],0,s.operand[slot],m0+(quad%2)*512,k*BK);
     SM90_TMA_LOAD_3D::copy(&amap,&s.ready[slot],0,s.operand[slot]+ASize,0,n0+(quad/2)*512,k*BK/64);
   }
 } else if(tid>=128) chain(s,tid,m0,n0,D);
}
'''
    if bn!=32:
        out=out.replace('quad<4','quad<'+str(quads))
        out=out.replace('m0+(quad%2)*512','m0').replace('n0+(quad/2)*512','n0+quad*512' if bn==64 else 'n0')
    out += encode
    out += '''
void init(){
 check(cudaFuncSetAttribute(direct_quadrants<cute::bfloat16_t>,cudaFuncAttributePreferredSharedMemoryCarveout,100),"BF carveout");
 check(cudaFuncSetAttribute(direct_quadrants<cute::half_t>,cudaFuncAttributePreferredSharedMemoryCarveout,100),"FP carveout");
 check(cudaFuncSetAttribute(direct_quadrants<cute::bfloat16_t>,cudaFuncAttributeMaxDynamicSharedMemorySize,sizeof(Shared<cute::bfloat16_t>)),"BF shared");
 check(cudaFuncSetAttribute(direct_quadrants<cute::half_t>,cudaFuncAttributeMaxDynamicSharedMemorySize,sizeof(Shared<cute::half_t>)),"FP shared");
}
void run(DType dtype,const void* A,const void* B,float* D,cudaStream_t stream){
 CUtensorMap a{},b{};encode(a,A,dtype,true,false);encode(b,B,dtype,false,false);
 if(dtype==DType::BF16) direct_quadrants<cute::bfloat16_t><<<dim3(16,8),Threads,sizeof(Shared<cute::bfloat16_t>),stream>>>(a,b,D);
 else direct_quadrants<cute::half_t><<<dim3(16,8),Threads,sizeof(Shared<cute::half_t>),stream>>>(a,b,D);
 check(cudaPeekAtLastError(),"direct launch");
}
} // namespace precision_research
'''
    if bn==64:out=out.replace('dim3(16,8)','dim3(8,16)')
    if bn==128:out=out.replace('dim3(16,8)','dim3(8,16)')
    # For BN=128 one tile covers 64 original columns and 128 original rows
    # (the multiplication is transposed); 16*8 tiles cover the complete output.
    if bn==128:out=out.replace('dim3(8,16)','dim3(8,16)')
    (ROOT/f'research/precision_20261016/direct_b{bn}_w{int(overlap)}.cuh').write_text(out)


if __name__=='__main__':
    ap=argparse.ArgumentParser()
    ap.add_argument('--bn',type=int,choices=[32,64,128],default=32)
    ap.add_argument('--overlap',action='store_true')
    args=ap.parse_args()
    generate(args.bn,args.overlap)
